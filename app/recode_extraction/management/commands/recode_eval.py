from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand, CommandError

from recode_extraction.services.evaluation import RecodeEvaluationService, dump_eval_json


class Command(BaseCommand):
    help = 'Evaluate extraction against RECODE-style corpus conventions and print metrics JSON.'

    def add_arguments(self, parser):
        parser.add_argument(
            '--index-path',
            default=str(Path(settings.BASE_DIR) / 'var' / 'recode_assets' / 'index.json'),
            help='Path to index.json generated by recode_fetch_assets',
        )
        parser.add_argument(
            '--text-root',
            default='',
            help='Optional directory containing plain-text files named <doc_id>.txt',
        )
        parser.add_argument(
            '--subset',
            type=int,
            default=0,
            help='Optional max number of documents to evaluate',
        )
        parser.add_argument(
            '--output-json',
            default='',
            help='Optional path to store machine-readable JSON metrics',
        )

    def handle(self, *args, **options):
        index_path = Path(options['index_path'])
        if not index_path.exists():
            raise CommandError(f'index.json not found: {index_path}')

        service = RecodeEvaluationService(
            index_path=index_path,
            text_root=options['text_root'] or None,
            subset=options['subset'] or None,
        )
        result = service.evaluate()

        payload = dump_eval_json(result, options['output_json'] or None)

        self.stdout.write('RECODE evaluation complete')
        self.stdout.write(payload)
